/**
 * Dedicated Integration Service for Boss URL Shortener VPS API
 * Endpoint: POST /api/links/stage1
 * Host: http://107.174.37.180
 *
 * Implements the sequential two-stage shortening workflow:
 * Step 1: Google AI Studio frontend generates the first-stage short URL (e.g. https://lnk.pro/abc123)
 * Step 2: This service dispatches { "url": firstStageShortUrl } to Boss VPS API (POST /api/links/stage1)
 * Step 3: Boss VPS backend creates the record in MariaDB and returns the authoritative stage1_url (e.g. http://107.174.37.180/s1_xyz).
 * Step 4: That real Boss URL is presented as the final result to the user.
 */

import { apiClient, Stage1LinkResponse } from './apiClient';

export interface VpsFinalShortenResult {
  success: boolean;
  finalShortUrl?: string;
  code?: string;
  id?: string;
  stage1Url?: string;
  originalUrl?: string;
  error?: {
    code: string;
    message: string;
    stage: 'stage1' | 'stage2';
  };
}

class VpsShortenerService {
  /**
   * Retrieves the centralized VPS Backend API Base URL from environment or saved config
   */
  public getBackendBaseUrl(): string {
    return apiClient.getBaseUrl();
  }

  /**
   * Dispatches the REAL first-stage short URL to Boss URL Shortener VPS:
   * POST /api/links/stage1
   * Body: { "url": firstStageShortUrl }
   */
  public async callVpsShorten(
    firstStageShortUrl: string,
    originalLongUrl: string
  ): Promise<VpsFinalShortenResult> {
    // 1. Pre-flight Validation of the first-stage short URL
    try {
      const parsedFirstStage = new URL(firstStageShortUrl);
      if (!['http:', 'https:'].includes(parsedFirstStage.protocol)) {
        return {
          success: false,
          error: {
            code: 'INVALID_STAGE1_URL',
            message: 'First-stage short URL must be a valid HTTP or HTTPS address.',
            stage: 'stage1',
          },
        };
      }
    } catch {
      return {
        success: false,
        error: {
          code: 'MALFORMED_STAGE1_URL',
          message: 'First-stage short URL generated by Google AI Studio is malformed.',
          stage: 'stage1',
        },
      };
    }

    // 2. Dispatch to Boss VPS API: POST /api/links/stage1
    // The request payload contains the actual first-stage short URL
    try {
      const res = await apiClient.createStage1Link(firstStageShortUrl);

      if (!res.success || !res.data) {
        return {
          success: false,
          stage1Url: firstStageShortUrl,
          originalUrl: originalLongUrl,
          error: {
            code: res.error?.code || 'BOSS_VPS_API_ERROR',
            message: res.error?.message || 'Boss URL Shortener VPS API failed to process the first-stage URL.',
            stage: 'stage2',
          },
        };
      }

      const bossData: Stage1LinkResponse = res.data;
      const finalUrl = bossData.stage1_url;

      if (!finalUrl) {
        return {
          success: false,
          stage1Url: firstStageShortUrl,
          originalUrl: originalLongUrl,
          error: {
            code: 'MISSING_BOSS_URL',
            message: 'Boss VPS API response did not contain a valid short URL.',
            stage: 'stage2',
          },
        };
      }

      return {
        success: true,
        finalShortUrl: finalUrl,
        code: bossData.stage1_code,
        id: String(bossData.stage1_id),
        stage1Url: firstStageShortUrl,
        originalUrl: originalLongUrl,
      };

    } catch (err: any) {
      return {
        success: false,
        stage1Url: firstStageShortUrl,
        originalUrl: originalLongUrl,
        error: {
          code: 'BOSS_CONNECTION_FAILURE',
          message: `Failed to connect to Boss URL Shortener VPS at ${this.getBackendBaseUrl()}: ${err.message}`,
          stage: 'stage2',
        },
      };
    }
  }

  /**
   * Diagnostic test method for Boss VPS /api/links/stage1 endpoint with latency tracking
   */
  public async testVpsEndpoint(testUrl: string): Promise<{
    reachable: boolean;
    latencyMs: number;
    requestPayload: { url: string };
    responseStatus?: number;
    responseBody?: any;
    error?: string;
  }> {
    const startTime = performance.now();
    const payload = { url: testUrl };

    try {
      const res = await apiClient.request<Stage1LinkResponse>('/api/links/stage1', {
        method: 'POST',
        body: JSON.stringify(payload),
      });

      const latencyMs = Math.round(performance.now() - startTime);

      return {
        reachable: res.success,
        latencyMs,
        requestPayload: payload,
        responseStatus: res.success ? 201 : 400,
        responseBody: res.data || res.error,
        error: res.error?.message,
      };
    } catch (err: any) {
      const latencyMs = Math.round(performance.now() - startTime);
      return {
        reachable: false,
        latencyMs,
        requestPayload: payload,
        error: err.message || 'Network request failed',
      };
    }
  }
}

export const vpsShortenerService = new VpsShortenerService();
